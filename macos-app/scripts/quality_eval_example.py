"""Create redistributable inputs for xtask quality-eval."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def create(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    expected = Image.new("RGB", (128, 96), "#eef2f8")
    ImageDraw.Draw(expected).rectangle((0, 80, 127, 95), fill="#172e49")
    expected.save(out / "expected.png")
    expected.save(out / "actual.png")
    damaged = expected.copy()
    damaged.putpixel((64, 88), (255, 255, 255))
    damaged.save(out / "damaged.png")
    checks: list[dict[str, object]] = [{"name":"dark footer", "category":"background", "page":1, "region":{"space":"image_px","canvas":[128,96],"rect":[0,80,128,96]}, "metric":{"kind":"image_diff","actual":"actual.png","expected":"expected.png","pixel_threshold":0,"max_changed_pixels":0}}]
    config: dict[str, object] = {"version":1,"provenance":{"input":"synthetic, generated by quality_eval_example.py"},"checks":checks}
    (out / "passing.json").write_text(json.dumps(config, indent=2)+"\n", encoding="utf-8")
    metric = checks[0]["metric"]
    assert isinstance(metric, dict)
    metric["actual"] = "damaged.png"
    (out / "failing.json").write_text(json.dumps(config, indent=2)+"\n", encoding="utf-8")
    comparison = Image.new("RGB", (1064, 250), "#edf1f6")
    draw = ImageDraw.Draw(comparison)
    draw.text((20, 12), "One damaged pixel: global average passes; named region fails", font=ImageFont.load_default(size=22), fill="#172e49")
    for index, (image, label) in enumerate([(expected,"Expected"),(damaged,"Damaged")]):
        draw.text((20 + index * 532, 56), label, font=ImageFont.load_default(size=20), fill="#172e49")
        comparison.paste(image.crop((0,80,128,96)).resize((512,128),Image.Resampling.NEAREST),(20+index*532,100))
    comparison.save(out / "comparison.png")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    create(parser.parse_args().out)


if __name__ == "__main__":
    main()
